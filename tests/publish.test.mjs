import assert from 'node:assert/strict';
import { test } from 'node:test';
import { execFileSync } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { nextVersion, appendEntry } from '../scripts/publish.mjs';

const root = process.cwd();
const publishedIndex = 'apiVersion: v1\nentries:\n  cody-execution:\n  - name: cody-execution\n    version: 0.6.9\n    digest: fixture\ngenerated: fixture\n';
test('Chart versions advance independently and retain old index entries', () => {
  const index = publishedIndex;
  assert.equal(nextVersion(index, '0.6.9'), '0.6.10');
  assert.equal(nextVersion(index, '1.0.0'), '1.0.0');
  const generated = 'apiVersion: v1\nentries:\n  cody-execution:\n  - version: 0.6.10\n    digest: abc\ngenerated: now\n';
  const updated = appendEntry(index, generated);
  assert.ok(updated.includes('  - version: 0.6.10\n    digest: abc\n'));
  assert.equal(updated.replace('  - version: 0.6.10\n    digest: abc\n', ''), index);
});

test('Verified source publishes once; generated commits and stale verification do not publish', () => {
  const directory = mkdtempSync(join(tmpdir(), 'chart-publication-test-'));
  const bare = join(directory, 'remote.git'), local = join(directory, 'checkout');
  const execute = (cmd, args, cwd = directory) => execFileSync(cmd, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  const git = args => execute('git', args, local);
  const publish = sha => execute(process.execPath, [resolve(root, 'scripts/publish.mjs'), sha], local);
  try {
    execute('git', ['init', '--bare', '-q', bare]);
    execute('git', ['clone', '-q', bare, local]);
    git(['config', 'user.name', 'Fixture']); git(['config', 'user.email', 'fixture@example.test']);
    git(['checkout', '-b', 'main']);
    cpSync('charts', join(local, 'charts'), { recursive: true });
    writeFileSync(join(local, 'index.yaml'), publishedIndex);
    const metadata = join(local, 'charts/cody-execution/Chart.yaml');
    writeFileSync(metadata, readFileSync(metadata, 'utf8').replace(/^version:.*$/m, 'version: 0.6.9'));
    git(['add', '.']); git(['commit', '-qm', 'Initial']); git(['push', '-u', 'origin', 'main']);
    git(['checkout', '-b', 'source-change']);
    writeFileSync(join(local, 'charts/cody-execution/values.yaml'), readFileSync(join(local, 'charts/cody-execution/values.yaml'), 'utf8') + '\n');
    git(['add', '.']); git(['commit', '-qm', 'Chart source']);
    git(['checkout', 'main']); git(['merge', '--no-ff', '-m', 'Merge chart source', 'source-change']); git(['push']);
    const verified = git(['rev-parse', 'HEAD']);
    assert.match(publish(verified), /Published chart 0.6.10/);
    const published = git(['rev-parse', 'HEAD']);
    assert.match(publish(verified), /already published/);
    assert.equal(git(['rev-parse', 'HEAD']), published);
    assert.match(publish(published), /No chart source changes/);
    assert.equal(git(['rev-parse', 'HEAD']), published);
    const controlPlan = join(directory, 'control.json');
    const controlPublish = () => execute(process.execPath, [resolve(root, 'scripts/publish.mjs'), verified, controlPlan, 'cody-control-plane'], local);
    assert.match(controlPublish(), /Published chart 0.4.1/);
    const controlIndex = readFileSync(join(local, 'index.yaml'), 'utf8');
    assert.ok(controlIndex.includes('  cody-execution:'));
    assert.ok(controlIndex.includes('  cody-control-plane:'));
    assert.equal(nextVersion(controlIndex, '0.4.1', 'cody-control-plane'), '0.4.2');
    assert.equal(nextVersion(controlIndex, '0.6.9'), '0.6.11');
    assert.match(controlPublish(), /already published/);
    assert.equal(JSON.parse(readFileSync(controlPlan, 'utf8')).archive, 'cody-control-plane-0.4.1.tgz');
    const archive = join(local, 'cody-execution-0.6.10.tgz');
    assert.equal(execute('helm', ['show', 'values', archive]), execute('helm', ['show', 'values', resolve(root, 'charts/cody-execution')]));
    writeFileSync(join(local, 'charts/cody-control-plane/values.yaml'), readFileSync(join(local, 'charts/cody-control-plane/values.yaml'), 'utf8') + '\n');
    git(['add', '.']); git(['commit', '-qm', 'Control only']); git(['push', 'origin', 'HEAD:main']);
    const controlOnly = git(['rev-parse', 'HEAD']);
    assert.match(publish(controlOnly), /No chart source changes/);
    assert.match(execute(process.execPath, [resolve(root, 'scripts/publish.mjs'), controlOnly, controlPlan, 'cody-control-plane'], local), /Published chart 0.4.2/);
    writeFileSync(join(local, 'charts/cody-execution/values.yaml'), readFileSync(join(local, 'charts/cody-execution/values.yaml'), 'utf8') + '\n');
    git(['add', '.']); git(['commit', '-qm', 'Source change before documentation']);
    writeFileSync(join(local, 'README.md'), 'Documentation-only tip of a multi-commit push');
    git(['add', '.']); git(['commit', '-qm', 'Documentation']); git(['push', 'origin', 'HEAD:main']);
    assert.match(publish(git(['rev-parse', 'HEAD'])), /Published chart 0.6.11/);
    assert.match(execute(process.execPath, [resolve(root, 'scripts/publish.mjs'), git(['rev-parse', 'HEAD']), controlPlan, 'cody-control-plane'], local), /No chart source changes/);
    const indexBeforeRepair=readFileSync(join(local,'index.yaml'));
    const archiveBeforeRepair=readFileSync(archive);
    const plan=join(directory,'repair.json');
    assert.match(execute(process.execPath,[resolve(root,'scripts/publish.mjs'),verified,plan],local),/already published/);
    const repaired=JSON.parse(readFileSync(plan,'utf8'));
    assert.equal(repaired.version,'0.6.10');assert.equal(repaired.sourceCommit,verified);assert.equal(repaired.publicationCommit,published);
    assert.deepEqual(readFileSync(archive),archiveBeforeRepair);
    assert.deepEqual(readFileSync(join(local,'index.yaml')),indexBeforeRepair);
    writeFileSync(join(local, 'charts/cody-execution/values.yaml'), readFileSync(join(local, 'charts/cody-execution/values.yaml'), 'utf8') + '\n');
    git(['add', '.']); git(['commit', '-qm', 'Next source']); git(['push', 'origin', 'HEAD:main']);
    const stale = git(['rev-parse', 'HEAD']);
    writeFileSync(join(local, 'charts/cody-execution/values.yaml'), readFileSync(join(local, 'charts/cody-execution/values.yaml'), 'utf8') + '\n');
    git(['add', '.']); git(['commit', '-qm', 'Newer source']); git(['push', 'origin', 'HEAD:main']);
    assert.match(publish(stale), /Newer chart source/);
  } finally { rmSync(directory, { recursive: true, force: true }); }
});
